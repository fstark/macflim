void packz32opt_test()
{
    std::vector<uint32_t> in0 = {0x00000000, 0x00000000, 0x00000000, 0x00000000, 0x00000001, 0x00000002,
                                 0x00000003, 0x00000000, 0x00000000, 0x00000005, 0x00000006, 0x00000007};
    std::vector<bool> in0b = {false, false, false, false, true, true, true, false, false, true, true, true};
    std::vector<run<uint32_t>> out0 = {run<uint32_t>{4, {1, 2, 3}}, run<uint32_t>{9, {5, 6, 7}}};

    auto res0 = pack<uint32_t>(std::begin(in0), std::begin(in0b), std::end(in0b), 1024, 1, 100);

    assert(res0 == out0);
}

